"use client";

import type { AnalysisResult, JdMatchResult, SkillGapResult, RecruiterSimulation } from "@/lib/engine";

const inr = (n: number) => (n >= 100000 ? `₹${(n / 100000).toFixed(1)}L` : `₹${(n / 1000).toFixed(0)}K`);

/**
 * Full report rendered only for printing / "Download report" (window.print()).
 * Hidden on screen via `hidden print:block`.
 *
 * `recruiter` is passed explicitly (the live, possibly JD-adjusted simulation)
 * so the printed verdict always matches what the dashboard shows.
 */
export function ReportPrint({
  result,
  recruiter,
  jd,
  gap,
}: {
  result: AnalysisResult;
  recruiter: RecruiterSimulation;
  jd: JdMatchResult | null;
  gap: SkillGapResult | null;
}) {
  const { fields, subScores, ats, careerPath, salary, benchmark, healthDashboard, aiInsights } = result;

  return (
    <div className="hidden print-block print:block" style={{ color: "#000" }}>
      <div style={{ padding: "8px 0", borderBottom: "2px solid #6d28d9", marginBottom: 16 }}>
        <h1 style={{ fontSize: 24, fontWeight: 800, margin: 0 }}>ResumeIQ — Career Intelligence Report</h1>
        <p style={{ fontSize: 12, color: "#555", margin: "4px 0 0" }}>
          {fields.name ?? "Candidate"} · {careerPath.bestFitRole} · Generated by KVAI Solutions
        </p>
      </div>

      <table style={{ width: "100%", borderCollapse: "collapse", marginBottom: 16 }}>
        <tbody>
          <tr>
            <td style={{ fontSize: 40, fontWeight: 800, color: "#6d28d9", width: 120 }}>{result.overallScore}<span style={{ fontSize: 16 }}>/100</span></td>
            <td style={{ fontSize: 13 }}>
              <strong>Grade {result.grade}</strong> · {benchmark.statement}<br />
              Recruiter verdict: <strong>{recruiter.decision}</strong> · Interview probability {recruiter.interviewProbability}% · Time-to-hire {recruiter.timeToHireDays} days<br />
              {recruiter.verdict}
            </td>
          </tr>
        </tbody>
      </table>

      <Section title="Score Breakdown">
        <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 12 }}>
          <tbody>
            {Object.values(subScores).map((d) => (
              <tr key={d.key} style={{ borderBottom: "1px solid #eee" }}>
                <td style={{ padding: "4px 0", width: 180 }}>{d.label}</td>
                <td style={{ fontWeight: 700, width: 50 }}>{d.score}</td>
                <td style={{ color: "#555" }}>{d.summary}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </Section>

      <Section title="Resume Health">
        <p style={{ fontSize: 12 }}>
          Career Health {healthDashboard.careerHealth} · Market Readiness {healthDashboard.marketReadiness} ·
          Employability {healthDashboard.employability} · Growth Potential {healthDashboard.growthPotential}<br />
          <strong>Strengths:</strong> {healthDashboard.strengths.join(", ") || "—"}<br />
          <strong>Focus areas:</strong> {healthDashboard.weaknesses.join(", ") || "—"}
        </p>
      </Section>

      <Section title="ATS Report">
        <List items={[...ats.missingSections.map((s) => `Missing: ${s}`), ...ats.atsRisks, ...ats.recommendations]} />
      </Section>

      {jd && (
        <Section title="Job Match">
          <p style={{ fontSize: 12 }}>
            Overall match {jd.matchPercentage}% · Skills {jd.skillsMatch}% · Experience {jd.experienceMatch}%<br />
            <strong>Missing skills:</strong> {jd.missingSkills.join(", ") || "none"}
          </p>
        </Section>
      )}

      <Section title="Salary Intelligence">
        <p style={{ fontSize: 12 }}>
          India: {inr(salary.india.min)} – {inr(salary.india.max)} · Remote: {inr(salary.remote.min)} – {inr(salary.remote.max)}<br />
          Basis: {salary.basis.join(" · ")}
        </p>
      </Section>

      <Section title="Career Roadmap">
        <List items={careerPath.roadmap.map((r) => `${r.stage} — ${r.description}`)} />
      </Section>

      {gap && (
        <Section title={`Skill Gap — ${gap.targetRole} (${gap.coverage}% coverage)`}>
          <p style={{ fontSize: 12 }}><strong>Missing:</strong> {gap.missingSkills.join(", ") || "none"}</p>
        </Section>
      )}

      {aiInsights && (
        <Section title="Improved Summary">
          <p style={{ fontSize: 12 }}>{aiInsights.improvedSummarySection}</p>
        </Section>
      )}

      <p style={{ fontSize: 10, color: "#888", marginTop: 20, borderTop: "1px solid #eee", paddingTop: 8 }}>
        © {new Date().getFullYear()} ResumeIQ · A KVAI Solutions product · resume.kvai.in
      </p>
    </div>
  );
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div style={{ marginBottom: 14 }}>
      <h2 style={{ fontSize: 14, fontWeight: 700, color: "#6d28d9", margin: "0 0 6px" }}>{title}</h2>
      {children}
    </div>
  );
}

function List({ items }: { items: string[] }) {
  return (
    <ul style={{ fontSize: 12, margin: 0, paddingLeft: 18, color: "#333" }}>
      {items.map((it, i) => <li key={i} style={{ marginBottom: 2 }}>{it}</li>)}
    </ul>
  );
}
